'use strict';
const assert=require('node:assert/strict');
const p=require('../docs/preview-ui.js');
const t=p.epoch('2026-11-25 03:00:00');
assert.equal(new Date(t).toISOString(),'2026-11-24T19:00:00.000Z');
assert.equal(p.label(t,'WITA'),'2026-11-25 03:00 WITA');
assert.equal(p.label(t,'UTC'),'2026-11-24 19:00 UTC');
assert.ok(Number.isNaN(p.epoch('2026-02-30 00:00:00')));
assert.ok(Number.isNaN(p.epoch('2026-11-25T03:00:00Z')));
assert.deepEqual(p.settings('?tz=UTC&hours=12'),{zone:'UTC',hours:12});
assert.deepEqual(p.settings('?tz=invalid&hours=1000'),{zone:'WITA',hours:24});
const r=[{Datetime:'2026-11-25 03:00:00',Rain:0},{Datetime:'2026-11-25 04:00:00',Rain:2},{Datetime:'2026-11-25 05:00:00',Rain:null},{Datetime:'2026-11-25 06:00:00',Rain:4}];
assert.equal(p.windowRows(r,t+1,2).length,2);
assert.deepEqual(p.cumulative(r).map(x=>x[1]),[0,2,null,null]);
assert.deepEqual(p.cumulative([r[0],r[3]]).map(x=>x[1]),[0,null]);
assert.equal(p.rainClass(null),'missing');assert.equal(p.rainClass(0),'zero');assert.equal(p.rainClass(12),'r5');
assert.deepEqual(p.barbParts(65),{flags:1,full:1,half:true,ring:false});
assert.equal(p.barbParts(0).ring,true);assert.equal(p.barbParts(null),null);
