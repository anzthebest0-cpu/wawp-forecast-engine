'use strict';
const assert=require('node:assert/strict');
const p=require('../docs/observation-ui.js');
const t=Date.parse('2026-11-25T04:00:00Z');
const valid={schema:'titan-local-awos-v1',station:'WAWP',source:'AWOSnet',observed_at_utc:'2026-11-25T03:59:00Z',wind_average_minutes:2,wind_reference:'true',units_confirmed:true,wind_speed_kt:0,temperature_c:30,dewpoint_c:24,qnh_hpa:1012};
const s=p.snapshot(valid,t);
assert.equal(s.values.wind_speed_kt,0);
assert.equal(s.values.gust_kt,null);
const extended=p.snapshot({...valid,altimeter_setting_hpa:1012.5,rain_current_hour_mm:0,relative_humidity_pct:70,source_epoch_offset_seconds:28900},t);
assert.equal(extended.values.rain_current_hour_mm,0);
assert.equal(extended.values.altimeter_setting_hpa,1012.5);
assert.equal(extended.epochOffset,28900);
assert.throws(()=>p.snapshot({...valid,relative_humidity_pct:101},t));
assert.equal(p.age(s.at,t,5).state,'recent');
assert.equal(p.age(s.at,t+360000,5).state,'stale');
for(const patch of [{station:'WAAA'},{wind_reference:'magnetic'},{units_confirmed:false},{wind_average_minutes:10},{observed_at_utc:'2026-11-25T04:01:00Z'},{observed_at_utc:'2026-02-30T04:00:00Z'},{wind_speed_kt:'0'},{gust_kt:-1},{dewpoint_c:40}])assert.throws(()=>p.snapshot({...valid,...patch},t));
const m=p.report('METAR WAWP 250330Z 00000KT CAVOK 30/24 Q1012 NOSIG=','2026-11-25',t);
assert.equal(p.age(m.at,t,60).state,'recent');
assert.equal(p.age(m.at,t+7200000,60).state,'stale');
assert.throws(()=>p.report('METAR WAWP 250330Z NIL','2026-11-25',t));
assert.throws(()=>p.report('METAR WAAA 250330Z 00000KT','2026-11-25',t));
assert.throws(()=>p.report('TAF WAWP 250330Z 00000KT','2026-11-25',t));
assert.throws(()=>p.report('METAR WAWP 250430Z 00000KT','2026-11-25',t));
assert.throws(()=>p.report('SPECI WAWP 240330Z 00000KT','2026-11-25',t));
assert.equal(p.report('SPECI COR WAWP 250330Z 00000KT','2026-11-25',t).at,m.at);
console.log('TITAN local observation checks passed');
